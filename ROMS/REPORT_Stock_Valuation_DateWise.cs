        public void udfnStockValuationReport(int varType)
        {
            try
            {
                string varGroupName = "-All-", varSubgroupName = "-All-";
                int varFlag = 0, varGroupCode = 0, varSubgroupCode = 0;

                if (txtGroup.Text.Trim() != "")
                {
                    varGroupName = txtGroup.Text.Trim();
                    varGroupCode = Convert.ToInt32(lblGroupCode.Text);
                }
                if (txtSubGroup.Text.Trim() != "")
                {
                    varSubgroupName = txtSubGroup.Text.Trim();
                    varSubgroupCode = Convert.ToInt32(lblSubGroupCode.Text);
                }
                if (Convert.ToInt32(cmbReportType.SelectedValue) == 422)
                {
                    varFlag = 1;
                }
                else if (Convert.ToInt32(cmbReportType.SelectedValue) == 423)
                {
                    varFlag = 2;
                }
                btnView.Enabled = false;
                lblNoRecordsFound.Visible = false;
                picLoader.Visible = true;
                RPTViewer.Visible = false;
                picLoader.BringToFront();
                Application.DoEvents();
                int varPrint = 0;
                DataSet objDs = new DataSet();
                SPDataService objspservice = new SPDataService();
                TRN_Stock objTRNG_Stock = new TRN_Stock();
                objTRNG_Stock.ViewType = 8;
                objTRNG_Stock.paraCOMID = Convert.ToInt32(cmbConcern.SelectedValue);
                objTRNG_Stock.paraUserLocations = MainForm.pbUserMappedLocationIds;
                objTRNG_Stock.paraGroupID = varGroupCode;
                objTRNG_Stock.paraSubGroupID = varSubgroupCode;
                objTRNG_Stock.paraFlag = varFlag;
                objTRNG_Stock.paraDate = dpFromDate.Text;
                objDs = objspservice.udfnStock(objTRNG_Stock);
                objspservice.CloseConnection();
                if (objDs != null) { if (objDs.Tables.Count > 0) { if (objDs.Tables[0].Rows.Count > 0) { varPrint = 1; } } }
                if (varPrint == 1)
                {
                    RPTViewer.Visible = true;
                    RPTViewer.BringToFront();
                    RPTViewer.ReuseParameterValuesOnRefresh = true;
                    RPTViewer.RefreshReport();
                    CrystalDecisions.CrystalReports.Engine.ReportDocument objBillreport = new CrystalDecisions.CrystalReports.Engine.ReportDocument();

                    objBillreport = new CrystalDecisions.CrystalReports.Engine.ReportDocument();
                    if (Convert.ToInt32(cmbReportType.SelectedValue) == 421)
                    {
                        objBillreport.Load(Application.StartupPath + "\\Reports\\RPT_Stock_Valuation_Groupwise.rpt");
                    }
                    else if (Convert.ToInt32(cmbReportType.SelectedValue) == 422)
                    {
                        objBillreport.Load(Application.StartupPath + "\\Reports\\RPT_Stock_Valuation_Subgroupwise.rpt");
                        objBillreport.SetParameterValue("paraGroupID", varGroupCode);
                        objBillreport.SetParameterValue("paraGroupName", varGroupName);
                    }
                    else if (Convert.ToInt32(cmbReportType.SelectedValue) == 423)
                    {
                        objBillreport.Load(Application.StartupPath + "\\Reports\\RPT_Stock_Valuation_Godownwise.rpt");
                        objBillreport.SetParameterValue("paraGroupID", varGroupCode);
                        objBillreport.SetParameterValue("paraGroupName", varGroupName);
                        objBillreport.SetParameterValue("paraSubGroupID", varSubgroupCode);
                        objBillreport.SetParameterValue("paraSubgroupName", varSubgroupName);
                    }
                    objBillreport.SetParameterValue("paraCOMID", Convert.ToInt32(cmbConcern.SelectedValue));
                    objBillreport.SetParameterValue("paraConcernName", Convert.ToString(cmbConcern.Text));
                    objBillreport.SetParameterValue("paraDate", dpFromDate.Text);
                    objBillreport.SetParameterValue("paraUserLocations", MainForm.pbUserMappedLocationIds);

                    objBillreport.SetParameterValue("paraHostName", MainForm.pbHostName);
                    objBillreport.SetParameterValue("paraUserName", MainForm.pbUserName);
                    objValidation.CrySqlConnection(objBillreport);
                    /* 0 - from view, 1- from telegram*/
                    if (varType == 0)
                    {
                        RPTViewer.ReportSource = objBillreport;
                        RPTViewer.Refresh();
                        //Btn_Print.Enabled = true;
                    }
                    else
                    {
                        MainForm.varcurrentdate = DateTime.Now.ToString("dd-MM-yyyy HH-mm tt");
                        string varReportName = "Stock Valuation By Date";
                        string varfilePath = MainForm.pbTelegramPath + "\\" + varReportName + "-" + MainForm.varcurrentdate + ".pdf";
                        if (File.Exists(varfilePath)) { File.Delete(varfilePath); }
                        objBillreport.ExportToDisk(CrystalDecisions.Shared.ExportFormatType.PortableDocFormat, varfilePath);
                        objMainForm.udfnSendToTelegram(varfilePath);
                        btnTelegram.Enabled = true;
                        MessageBox.Show("Sent Successfully!", "Information", MessageBoxButtons.OK, MessageBoxIcon.Information);
                    }
                }
